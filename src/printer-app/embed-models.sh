# Writes C source with every model manifest under MODELS_DIR embedded:
# each model's model.json and its three icons as byte arrays, plus the
# table phomemo_embedded_models[].
#
#   sh embed-models.sh MODELS_DIR > models_data.c

set -eu

dir=$1

bytes() {
  od -An -v -tx1 "$1" | sed 's/ \([0-9a-f][0-9a-f]\)/0x\1,/g'
}

printf '// Generated by embed-models.sh from %s; do not edit.\n' "$dir"
printf '#include "phomemo.h"\n\n'

ids=""
for json in "$dir"/*/model.json; do
  [ -f "$json" ] || continue
  id=$(basename "$(dirname "$json")")
  sym=$(printf '%s' "$id" | tr -c 'a-z0-9\n' '_')
  ids="$ids $id"
  printf 'static const unsigned char %s_json[] = {\n' "$sym"
  bytes "$json"
  printf '0x00};\n'
  for size in 48 128 512; do
    icon="$dir/$id/icon-$size.png"
    if [ -f "$icon" ]; then
      printf 'static const unsigned char %s_icon_%s[] = {\n' "$sym" "$size"
      bytes "$icon"
      printf '};\n'
    fi
  done
  printf '\n'
done

printf 'const phomemo_embedded_model_t phomemo_embedded_models[] = {\n'
count=0
for id in $ids; do
  sym=$(printf '%s' "$id" | tr -c 'a-z0-9\n' '_')
  printf '  {"%s", (const char *)%s_json, {' "$id" "$sym"
  for size in 48 128 512; do
    if [ -f "$dir/$id/icon-$size.png" ]; then
      printf '{%s_icon_%s, sizeof(%s_icon_%s)}, ' "$sym" "$size" "$sym" "$size"
    else
      printf '{NULL, 0}, '
    fi
  done
  printf '}},\n'
  count=$((count + 1))
done
[ "$count" -gt 0 ] || printf '  {NULL, NULL, {{NULL, 0}, {NULL, 0}, {NULL, 0}}},\n'
printf '};\nconst int phomemo_num_embedded_models = %d;\n' "$count"
