#!/bin/sh
# Emits a C source file holding the printer icons as byte arrays.
#   sh icons/embed.sh icons/m08f-48.png icons/m08f-128.png icons/m08f-512.png
set -eu

printf '// Generated by icons/embed.sh; do not edit.\n#include <stddef.h>\n\n'
for file in "$@"; do
  name=$(basename "$file" .png | tr '-' '_')
  printf 'const unsigned char phomemo_icon_%s[] = {\n' "$name"
  od -An -v -tx1 "$file" | sed 's/ \([0-9a-f][0-9a-f]\)/0x\1,/g'
  printf '};\nconst size_t phomemo_icon_%s_len = sizeof(phomemo_icon_%s);\n\n' "$name" "$name"
done
